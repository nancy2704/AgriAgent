"""AgriAgent — Pydantic schemas for input/output validation."""
from __future__ import annotations

from datetime import date
from typing import Optional
from pydantic import BaseModel, Field, field_validator


# ---------------------------------------------------------------------------
# Input Models
# ---------------------------------------------------------------------------

class FarmerInput(BaseModel):
    """Validated farmer problem submission."""

    crop_name: str = Field(..., min_length=1, max_length=100, description="Name of the crop")
    location: str = Field(..., min_length=1, max_length=200, description="Farm location (city, region, or country)")
    symptoms: str = Field(..., min_length=5, max_length=2000, description="Observed symptoms")
    symptom_duration: Optional[str] = Field(None, max_length=100, description="How long symptoms have been observed")
    additional_notes: Optional[str] = Field(None, max_length=1000, description="Any other relevant details")

    @field_validator("crop_name", "location", "symptoms", mode="before")
    @classmethod
    def strip_whitespace(cls, v: str) -> str:
        if isinstance(v, str):
            return v.strip()
        return v

    @field_validator("symptoms")
    @classmethod
    def symptoms_not_trivial(cls, v: str) -> str:
        if len(v.split()) < 2:
            raise ValueError("Symptoms description must contain at least two words.")
        return v


# ---------------------------------------------------------------------------
# Knowledge / Research Models
# ---------------------------------------------------------------------------

class KnowledgeEntry(BaseModel):
    """A single entry from the agricultural knowledge base."""
    id: str
    crop: str
    topic: str
    content: str
    source_title: str
    source_url: Optional[str] = None
    severity: str = "unknown"
    relevance_score: float = 0.0


class ResearchResult(BaseModel):
    """Output from the Agricultural Research Agent."""
    entries: list[KnowledgeEntry] = Field(default_factory=list)
    is_demo: bool = False
    note: Optional[str] = None


# ---------------------------------------------------------------------------
# Weather Models
# ---------------------------------------------------------------------------

class WeatherData(BaseModel):
    """Structured weather information."""
    location: str
    temperature_c: Optional[float] = None
    humidity_pct: Optional[float] = None
    description: Optional[str] = None
    wind_speed_ms: Optional[float] = None
    rainfall_mm: Optional[float] = None
    forecast_summary: Optional[str] = None
    is_demo: bool = False
    error: Optional[str] = None


# ---------------------------------------------------------------------------
# Action Plan Models
# ---------------------------------------------------------------------------

class ActionStep(BaseModel):
    """A single step in the action plan."""
    step_number: int
    action: str
    rationale: str
    urgency: str = Field(default="normal", description="low | normal | high | urgent")


class ActionPlan(BaseModel):
    """Structured action plan produced by the Planning Agent."""
    summary: str
    likely_issues: list[str] = Field(default_factory=list)
    steps: list[ActionStep] = Field(default_factory=list)
    observations_needed: list[str] = Field(default_factory=list)
    expert_consultation_recommended: bool = False
    uncertainty_notes: Optional[str] = None
    disclaimer: str = (
        "This plan is generated by an AI assistant to support — not replace — "
        "advice from a qualified agricultural expert. Always consult a local "
        "agronomist for critical decisions and before applying any chemical treatments."
    )


# ---------------------------------------------------------------------------
# Follow-up Models
# ---------------------------------------------------------------------------

class FollowUpTask(BaseModel):
    """A follow-up task for the farmer."""
    task_description: str = Field(..., min_length=3, max_length=500)
    due_date: Optional[date] = None
    report_id: Optional[int] = None


class FollowUpTaskUpdate(BaseModel):
    """Used to update a follow-up task."""
    task_id: int
    status: str = Field(..., pattern="^(pending|completed|skipped)$")
    observation_notes: Optional[str] = Field(None, max_length=1000)


# ---------------------------------------------------------------------------
# Workflow Models
# ---------------------------------------------------------------------------

class WorkflowResult(BaseModel):
    """Complete output from one AgriAgent workflow run."""
    query_id: Optional[int] = None
    report_id: Optional[int] = None
    farmer_input: FarmerInput
    research: ResearchResult
    weather: WeatherData
    action_plan: ActionPlan
    sources: list[KnowledgeEntry] = Field(default_factory=list)
    is_demo: bool = False
